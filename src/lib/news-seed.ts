export type SeedNewsResult = { created: number; updated: number };

/** Записва или обновява началните новини. Идемпотентно — сверява по slug. */
export async function seedNews(authorId: string): Promise<SeedNewsResult> {
  let created = 0;
  let updated = 0;

  for (const item of SEED_NEWS) {
    const existing = await prisma.newsItem.findUnique({
      where: { slug: item.slug },
      select: { id: true },
    });

    const data = {
      title: item.title,
      summary: item.summary,
      body: item.body,
      category: item.category,
      eventDate: item.eventDate ? new Date(item.eventDate) : null,
      eventEndDate: item.eventEndDate ? new Date(item.eventEndDate) : null,
      location: item.location ?? null,
      sourceUrl: item.sourceUrl ?? null,
      sourceName: item.sourceName ?? null,
    };

    await prisma.newsItem.upsert({
      where: { slug: item.slug },
      create: {
        ...data,
        slug: item.slug || slugify(item.title),
        authorId,
        published: true,
      },
      update: data,
    });

    if (existing) updated++;
    else created++;
  }

  return { created, updated };
}
