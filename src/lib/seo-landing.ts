export function categoryLandingFor(category: string | null | undefined) {
  if (!category) return undefined;
  return CATEGORY_LANDINGS.find((c) => c.category === category);
}

/* ------------------------------ Области ------------------------------ */

export type RegionLanding = { slug: string; region: Region; label: string };

/** „София (столица)“ → „София“; останалите се четат като „област Пловдив“. */
function regionLabel(region: Region) {
  if (region === "София (столица)") return "София";
  if (region === "София (област)") return "Софийска област";
  return `област ${region}`;
}

export const REGION_LANDINGS: RegionLanding[] = REGIONS.map((region) => ({
  slug: slugify(region),
  region,
  label: regionLabel(region),
}));

export function regionLandingBySlug(slug: string) {
  return REGION_LANDINGS.find((r) => r.slug === slug);
}

export function regionLandingFor(region: string | null | undefined) {
  if (!region) return undefined;
  return REGION_LANDINGS.find((r) => r.region === region);
}
